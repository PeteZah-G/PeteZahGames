export function isGHref(u: string): boolean {
  const b = hrefs.g();
  return u === b || u.startsWith(b + "?");
}

export function isGvHref(u: string): boolean {
  const b = hrefs.gv();
  return u === b || u.startsWith(b + "?");
}

export function brandMarkSrc(): string {
  return "/logo.png";
}

export function defaultBrandSrc(): string {
  try {
    return localStorage.getItem("siteLogo") || "/logo.png";
  } catch {
    return "/logo.png";
  }
}

export function isHomeHost(): boolean {
  try {
    const h = window.location.hostname.replace(/^www\./, "").toLowerCase();
    return h === hrefs.homeHost();
  } catch {
    return false;
  }
}
